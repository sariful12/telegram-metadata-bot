"""Metadata scanner + pixel-only cleaner.

Mirrors the detection rules of the Image Metadata Remover web tool
(github.com/sariful12/image-metadata-remover, index.html):

* Scan: walk the file's own structure (JPEG APP segments, PNG chunks,
  WebP RIFF chunks) plus a printable-ASCII sweep of the whole file, and
  flag AI markers with the same AI_HINTS list the web tool uses
  (C2PA / Content Credentials, XMP labels from ChatGPT, DALL-E,
  Firefly, Midjourney, ...).
* Clean: rebuild the image from pixels only (Pillow), same size,
  JPEG quality 95, PNG lossless, WebP quality 95, no metadata carried
  over. Orientation stored in EXIF is baked into the pixels first, so
  the cleaned image looks the same as the original.

Honest limit (same as the web tool): invisible watermarks hidden
*inside the pixels* (e.g. Google's SynthID) are part of the picture,
not metadata, so no metadata remover can take them out.
"""

from __future__ import annotations

import re
import struct
from io import BytesIO
from pathlib import Path

from PIL import Image, ImageOps

# --- detection rules copied from the web tool -------------------------------

AI_HINTS = [
    "c2pa", "content credentials", "contentcredentials", "adobe firefly",
    "firefly", "dall", "openai", "chatgpt", "midjourney",
    "stable diffusion", "automatic1111", "comfyui", "imagen", "gemini",
    "google ai", "synthid", "ai generated", "ai-generated",
    "generated by ai", "dreamstudio", "leonardo", "ideogram",
    "bing image creator", "microsoft designer", "gencraft", "flux",
]

SUPPORTED_FORMATS = {"JPEG", "PNG", "WEBP"}
SUPPORTED_EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp"}

JPEG_QUALITY = 95
WEBP_QUALITY = 95

# EXIF tag numbers (Pillow's Image.ExifTags.IFD equivalents)
_TAG_MAKE = 0x010F
_TAG_MODEL = 0x0110
_TAG_SOFTWARE = 0x0131
_TAG_GPS_INFO = 0x8825


# --- byte helpers -----------------------------------------------------------

def _u16be(data: bytes, off: int) -> int:
    return struct.unpack_from(">H", data, off)[0]


def _u32be(data: bytes, off: int) -> int:
    return struct.unpack_from(">I", data, off)[0]


def _bytes_to_text(data: bytes, start: int, length: int) -> str:
    """Printable-ASCII view of a byte range (non-printable -> space)."""
    end = min(len(data), start + length)
    return "".join(chr(c) if 32 <= c < 127 else " " for c in data[start:end])


def _ascii_runs(data: bytes) -> str:
    """Printable ASCII runs (>= 4 chars) joined with newlines."""
    runs, cur = [], ""
    for c in data:
        if 32 <= c < 127:
            cur += chr(c)
            if len(cur) > 4000:
                runs.append(cur)
                cur = ""
        else:
            if len(cur) >= 4:
                runs.append(cur)
            cur = ""
    if len(cur) >= 4:
        runs.append(cur)
    return "\n".join(runs)


def _find_ai(text: str) -> list[str]:
    low = text.lower()
    return [hint for hint in AI_HINTS if hint in low]


def _grab(text: str, pattern: str) -> str | None:
    m = re.search(pattern, text, re.IGNORECASE)
    return m.group(1).strip()[:120] if m else None


# --- format-specific scans (mirror the web tool's scanJPEG/PNG/WebP) ------

def _scan_jpeg(data: bytes) -> list[dict]:
    found = []
    if len(data) < 2 or data[0] != 0xFF or data[1] != 0xD8:
        return found
    off = 2
    while off + 4 <= len(data):
        if data[off] != 0xFF:
            break
        marker = data[off + 1]
        if marker == 0xDA:  # start of scan — image data begins
            break
        length = _u16be(data, off + 2)
        if length < 2:
            break
        seg_start, seg_len = off + 4, length - 2
        if marker == 0xE1:  # APP1: EXIF, XMP or other (incl. C2PA-adjacent)
            head = _bytes_to_text(data, seg_start, min(29, seg_len))
            if head.startswith("Exif"):
                found.append({"label": "EXIF data block",
                              "value": "camera, date & settings data present",
                              "ai": False})
            elif head.startswith("http://ns.adobe.com/xap/1.0/"):
                xmp = _bytes_to_text(data, seg_start, seg_len)
                found.append({"label": "XMP metadata block",
                              "value": "labels & edit history present",
                              "ai": bool(_find_ai(xmp))})
            else:
                other = _bytes_to_text(data, seg_start, min(seg_len, 4000))
                if _find_ai(other):
                    found.append({"label": "AI / C2PA data block",
                                  "value": "AI or Content Credentials data present",
                                  "ai": True})
        elif marker == 0xEB:  # APP11: C2PA JUMBF lives here
            head = _bytes_to_text(data, seg_start, min(29, seg_len))
            if "JUMBF" in head:
                body = _bytes_to_text(data, seg_start, min(seg_len, 4000))
                found.append({"label": "AI / C2PA data block",
                              "value": "AI or Content Credentials data present",
                              "ai": bool(_find_ai(body))})
        elif marker == 0xED:  # APP13: IPTC
            found.append({"label": "IPTC data block",
                          "value": "caption / credit data present",
                          "ai": False})
        elif marker == 0xFE:  # COM: comment
            comment = _bytes_to_text(data, seg_start, seg_len).strip()
            if comment:
                found.append({"label": "Comment", "value": comment,
                              "ai": bool(_find_ai(comment))})
        off += 2 + length
    return found


def _scan_png(data: bytes) -> list[dict]:
    found = []
    sig = bytes([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A])
    if data[:8] != sig:
        return found
    off = 8
    while off + 12 <= len(data):
        length = _u32be(data, off)
        chunk_type = _bytes_to_text(data, off + 4, 4)
        data_start = off + 8
        if chunk_type in ("tEXt", "iTXt", "zTXt"):
            raw = _bytes_to_text(data, data_start, min(length, 6000))
            key = re.sub(r"[^A-Za-z0-9 _-]", "", raw.split(" ")[0])[:40] or "text"
            val = raw[len(key):].strip()[:140]
            found.append({"label": f"PNG text chunk ({key})",
                          "value": val or "embedded text data",
                          "ai": bool(_find_ai(raw))})
        elif chunk_type == "eXIf":
            found.append({"label": "EXIF data block",
                          "value": "camera, date & settings data present",
                          "ai": False})
        elif chunk_type == "iCCP":
            found.append({"label": "Embedded colour profile (ICC)",
                          "value": "", "ai": False})
        elif chunk_type == "tIME":
            found.append({"label": "Last-modified time chunk",
                          "value": "", "ai": False})
        if chunk_type in ("IDAT", "IEND"):
            break
        off += 12 + length
    return found


def _scan_webp(data: bytes) -> list[dict]:
    found = []
    if _bytes_to_text(data, 0, 4) != "RIFF" or _bytes_to_text(data, 8, 4) != "WEBP":
        return found
    off = 12
    while off + 8 <= len(data):
        chunk_type = _bytes_to_text(data, off, 4)
        length = struct.unpack_from("<I", data, off + 4)[0]
        if chunk_type == "EXIF":
            found.append({"label": "EXIF data block",
                          "value": "camera, date & settings data present",
                          "ai": False})
        elif chunk_type == "XMP ":
            xmp = _bytes_to_text(data, off + 8, length)
            found.append({"label": "XMP metadata block",
                          "value": "labels & edit history present",
                          "ai": bool(_find_ai(xmp))})
        elif chunk_type == "ICCP":
            found.append({"label": "Embedded colour profile (ICC)",
                          "value": "", "ai": False})
        off += 8 + length + (length % 2)
    return found


# --- whole-file scan (mirror the web tool's scanFile) -----------------------

def scan_bytes(data: bytes, fmt: str) -> dict:
    """Scan raw image bytes. Returns {"found": [...], "ai": bool}."""
    if fmt == "JPEG":
        found = _scan_jpeg(data)
    elif fmt == "PNG":
        found = _scan_png(data)
    elif fmt == "WEBP":
        found = _scan_webp(data)
    else:
        found = []

    text = _ascii_runs(data)

    software = (
        _grab(text, r"Software[:\s=]+([ -~]{2,60})")
        or _grab(text, r"<tiff:Software>([^<]{2,80})<")
        or _grab(text, r'"Software"\s*:\s*"([^"]{2,80})"')
    )
    make = _grab(text, r"<tiff:Make>([^<]{2,60})<")
    model = _grab(text, r"<tiff:Model>([^<]{2,60})<")
    desc = (
        _grab(text, r"<dc:description>[\s\S]{0,60}?<rdf:li[^>]*>([^<]{2,120})<")
        or _grab(text, r"ImageDescription[:\s=]+([ -~]{2,100})")
    )
    params = _grab(text, r"parameters[:\s]+([ -~]{4,160})")
    has_gps_text = bool(re.search(r"GPSLatitude|GPSLongitude|gps", text, re.I)
                        and re.search(r"GPS", text))

    if software:
        found.append({"label": "Software", "value": software,
                      "ai": bool(_find_ai(software))})
    if make or model:
        found.append({"label": "Camera / device",
                      "value": " ".join(x for x in (make, model) if x),
                      "ai": False})
    if desc:
        found.append({"label": "Description", "value": desc,
                      "ai": bool(_find_ai(desc))})
    if params:
        found.append({"label": "AI generation parameters", "value": params,
                      "ai": True})
    if has_gps_text:
        found.append({"label": "GPS location data",
                      "value": "coordinates embedded in file", "ai": False})

    ai_hits = _find_ai(text)
    has_ai_label = bool(ai_hits) or any(item["ai"] for item in found)
    if has_ai_label and not any(item["ai"] for item in found):
        found.append({"label": "AI label data",
                      "value": "AI-related metadata text found in file",
                      "ai": True})

    # de-duplicate by label+value, keep the web tool's 10-item cap
    seen, out = set(), []
    for item in found:
        key = item["label"] + "|" + item["value"]
        if key not in seen:
            seen.add(key)
            out.append(item)
    return {"found": out[:10], "ai": has_ai_label}


# --- cleaning ---------------------------------------------------------------

def _detect_format(data: bytes) -> str | None:
    if data[:2] == b"\xff\xd8":
        return "JPEG"
    if data[:8] == bytes([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]):
        return "PNG"
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return "WEBP"
    return None


def clean_image(in_path: str | Path, out_path: str | Path) -> dict:
    """Strip all metadata from an image by rebuilding it from pixels.

    Returns a report dict: format, size, what was found/removed, whether
    an AI label was present, and whether the output re-scan is clean.
    Raises ValueError for unsupported or unreadable files.
    """
    in_path, out_path = Path(in_path), Path(out_path)
    data = in_path.read_bytes()
    fmt = _detect_format(data)
    if fmt is None:
        raise ValueError("not a JPG, PNG or WebP image")

    try:
        img = Image.open(BytesIO(data))
        img.load()
    except Exception as exc:  # corrupt / unreadable image
        raise ValueError("could not read this image file") from exc
    if img.format not in SUPPORTED_FORMATS:
        raise ValueError("only JPG, PNG and WebP are supported")

    scan = scan_bytes(data, fmt)
    found = list(scan["found"])

    # Pillow-level EXIF check: catches binary EXIF (Make/Model/Software/
    # GPS) that the ASCII sweep cannot see.
    try:
        exif = img.getexif()
    except Exception:
        exif = None
    if exif:
        if not any(item["label"] == "EXIF data block" for item in found):
            found.append({"label": "EXIF data block",
                          "value": "camera, date & settings data present",
                          "ai": False})
        make = exif.get(_TAG_MAKE)
        model = exif.get(_TAG_MODEL)
        if (make or model) and not any(
                item["label"] == "Camera / device" for item in found):
            found.append({"label": "Camera / device",
                          "value": " ".join(str(x) for x in (make, model) if x),
                          "ai": False})
        software = exif.get(_TAG_SOFTWARE)
        if software and not any(item["label"] == "Software" for item in found):
            found.append({"label": "Software", "value": str(software),
                          "ai": bool(_find_ai(str(software)))})
        try:
            gps_ifd = exif.get_ifd(_TAG_GPS_INFO)
        except Exception:
            gps_ifd = None
        if gps_ifd and not any(item["label"] == "GPS location data"
                               for item in found):
            found.append({"label": "GPS location data",
                          "value": "coordinates embedded in file",
                          "ai": False})

    width, height = img.size

    # Rebuild from pixels only. exif_transpose bakes any EXIF orientation
    # into the pixels first, so the cleaned image looks the same.
    img = ImageOps.exif_transpose(img)
    if fmt == "JPEG":
        if img.mode in ("RGBA", "LA", "PA"):
            bg = Image.new("RGB", img.size, (255, 255, 255))
            bg.paste(img, mask=img.split()[-1])
            img = bg
        elif img.mode != "RGB":
            img = img.convert("RGB")
        img.save(out_path, format="JPEG", quality=JPEG_QUALITY,
                 optimize=True)
    elif fmt == "PNG":
        img.save(out_path, format="PNG", optimize=True)
    else:  # WEBP
        img.save(out_path, format="WEBP", quality=WEBP_QUALITY, method=6)

    # Verify the output really is clean by re-scanning it.
    out_data = Path(out_path).read_bytes()
    out_scan = scan_bytes(out_data, fmt)
    verified_clean = not out_scan["found"] and not out_scan["ai"]

    removed = [item["label"] for item in found]
    return {
        "format": fmt,
        "width": width,
        "height": height,
        "found": found,
        "removed": removed,
        "ai_label": scan["ai"],
        "already_clean": not found,
        "out_size": len(out_data),
        "verified_clean": verified_clean,
    }
